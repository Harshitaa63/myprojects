def _adzuna_request(country: str, what: str, where: str, days: int, max_results: int):
    """Fetch one page from Adzuna for a single country."""
    url = f"https://api.adzuna.com/v1/api/jobs/{country}/search/1"
    params = {
        "app_id": APP_ID,
        "app_key": APP_KEY,
        "results_per_page": max_results,
        "what": what,
        "where": where,
        "sort_by": "date",
        "max_days_old": int(days),
        "content-type": "application/json",
    }
    r = requests.get(url, params=params, timeout=20)
    r.raise_for_status()
    return r.json().get("results", [])

def _filter_client_side(rows, keyword: str, remote_only: bool):
    """Tighten results so typing 'DevOps' really shows DevOps, and filter remote if asked."""
    if not rows:
        return rows
    kw = keyword.strip().lower()
    out = []
    for it in rows:
        title = (it.get("title") or "")
        desc  = (it.get("description") or "")
        loc   = (((it.get("location") or {}) or {}).get("display_name") or "")
        # Keyword must appear in title OR description (case-insensitive)
        if kw and (kw not in title.lower() and kw not in desc.lower()):
            continue
        if remote_only:
            if ("remote" not in title.lower()
                and "remote" not in desc.lower()
                and "remote" not in loc.lower()):
                continue
        out.append(it)
    return out

def _normalize(rows, country_code: str):
    """Convert raw Adzuna rows to a clean table."""
    norm = []
    for j in rows:
        norm.append({
            "title": j.get("title",""),
            "company": ((j.get("company") or {}) or {}).get("display_name",""),
            "country": country_code.upper(),
            "location": ((j.get("location") or {}) or {}).get("display_name",""),
            "posted_at": j.get("created",""),
            "url": j.get("redirect_url",""),
            "description": j.get("description",""),
        })
    df = pd.DataFrame(norm)
    if not df.empty:
        df["posted_at"] = pd.to_datetime(df["posted_at"], errors="coerce")
        df = df.sort_values("posted_at", ascending=False).reset_index(drop=True)
    return df

def _render_html(df: pd.DataFrame) -> str:
    if df is None or df.empty:
        return "<div>No matching jobs.</div>"
    items = []
    for _, r in df.iterrows():
        t = (r["title"] or "(no title)")
        c = (r["company"] or "(no company)")
        u = (r["url"] or "#")
        l = (r["location"] or "")
        cc = (r["country"] or "")
        d = ""
        if pd.notna(r["posted_at"]):
            try:
                d = r["posted_at"].date().isoformat()
            except Exception:
                d = ""
        items.append(
            f'<li style="margin:6px 0">'
            f'<a href="{u}" target="_blank" rel="noopener noreferrer">{t}</a>'
            f' — {c} ({cc}{", " + l if l else ""}) · {d}'
            f"</li>"
        )
    return "<ol>" + "".join(items) + "</ol>"

