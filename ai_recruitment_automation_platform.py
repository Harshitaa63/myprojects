def analyze(jd_text, resume_file):
    jd_text = (jd_text or "").strip()
    if not jd_text:
        return "0.0", "Please paste a job description.", "—"

    resume_text = read_file_text(resume_file)
    if not resume_text or isinstance(resume_text, str) and resume_text.startswith("Error reading file:"):
        return "0.0", "Please upload a readable resume (PDF/DOCX/TXT).", "—"

    # Extract JD skills/tools/responsibilities
    jd_json_raw = call_llm(PROMPT_JSON.format(jd=jd_text[:12000]))
    jd_obj = safe_json(jd_json_raw)
    musts = [s.strip() for s in jd_obj.get("must_have", []) if str(s).strip()]
    tools = [s.strip() for s in jd_obj.get("tools", []) if str(s).strip()]
    resp  = [s.strip() for s in jd_obj.get("responsibilities", []) if str(s).strip()]

    # Coverage for simple score
    def cov(terms):
        if not terms: return 0.0
        hits = sum(1 for t in terms if contains_relaxed(resume_text, t))
        return hits / max(1, len(terms))
    score = (0.6*cov(musts) + 0.25*cov(tools) + 0.15*cov(resp)) * 100.0
    score_pct = round(float(score), 1)

    #Missing items to add in SKILLS section (top 10)
    missing_musts = [t for t in musts if not contains_relaxed(resume_text, t)]
    missing_tools = [t for t in tools if not contains_relaxed(resume_text, t)]
    skills_changes_list = (missing_musts + missing_tools)[:10]
    if skills_changes_list:
        skills_changes = "\n".join(f"• Add/Emphasize: {s}" for s in skills_changes_list)
    else:
        skills_changes = "• Skills section already covers the core requirements. Consider re-ordering to put the most relevant first."

    #Overall resume change suggestions (LLM)
    advice = call_llm(PROMPT_SUGGEST.format(jd=jd_text[:12000], resume=resume_text[:12000]))
    # Try to parse [MatchPercent]
    m = re.search(r"\[MatchPercent\]\s*([0-9]+(?:\.[0-9]+)?)", advice)
    if m:
        try:
            score_pct = float(m.group(1))
        except Exception:
            pass
    # Extract [OverallChanges]
    w = re.search(r"\[OverallChanges\](.*)$", advice, re.DOTALL | re.IGNORECASE)
    overall_changes = (w.group(1).strip() if w else advice.strip())
    # make sure bullets look clean
    if not overall_changes.startswith("-") and "•" not in overall_changes[:5]:
        overall_changes = "\n".join("- " + line.strip() for line in overall_changes.splitlines() if line.strip())

    return f"{score_pct}", skills_changes, overall_changes

