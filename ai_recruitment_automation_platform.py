DEFAULT_CAL = "https://calendly.com/your-link/30min"

def propose_slots():
    now = dt.datetime.now()
    slots = []
    day = 0
    while len(slots) < 9 and day < 10:
        d = now + dt.timedelta(days=day+1)
        if d.weekday() < 5:
            for hr in (10, 14, 16):
                slots.append(d.replace(hour=hr, minute=0, second=0, microsecond=0).strftime("%a %b %d, %I:%M %p CT"))
        day += 1
    return slots[:9]

