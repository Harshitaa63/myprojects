def parse_lines(text: str) -> pd.DataFrame:
    rows = []
    for line in (text or "").splitlines():
        parts = [p.strip() for p in line.split("|")]
        if len(parts) >= 3:
            rows.append({"from":parts[0], "subject":parts[1], "body":parts[2], "date":parts[3] if len(parts)>3 else ""})
    return pd.DataFrame(rows)

def load_messages(file, pasted):
    if file is not None:
        try:
            df = pd.read_csv(file.name)
        except Exception as e:
            return pd.DataFrame(SAMPLE), f"❌ CSV error: {e}"
    else:
        df = parse_lines(pasted)
        if df.empty: df = pd.DataFrame(SAMPLE)
    for c in ["from","subject","body","date"]:
        if c not in df.columns: df[c] = ""
    return df[["from","subject","body","date"]].copy(), "✅ Loaded."

def run_classify(df, use_llm, mode, filt):
    if df.empty: return df, 0, ""
    labels, confs = [], []
    for _, r in df.iterrows():
        L, C = classify_rules(r["subject"], r["body"])
        if C == 0 and use_llm:
            L, C = classify_llm(r["subject"], r["body"], mode)
        labels.append(L); confs.append(C)
    out = df.copy()
    out["label"], out["confidence"] = labels, confs
    if filt and filt != "All":
        out = out[out["label"] == filt]
    preview = ""
    if not out.empty:
        r = out.iloc[0].to_dict()
        preview = f"From: {r.get('from','')}\nSubject: {r.get('subject','')}\n\n{r.get('body','')}"
    return out, 0, preview

def show_row(df, idx):
    if df.empty: return ""
    idx = int(max(0, min(len(df)-1, int(idx))))
    r = df.iloc[idx].to_dict()
    return f"From: {r.get('from','')}\nSubject: {r.get('subject','')}\n\n{r.get('body','')}"

def do_reply(df, idx, intent, extra, cal, mode):
    if df.empty: return "No message selected."
    idx = int(max(0, min(len(df)-1, int(idx))))
    row = df.iloc[idx].to_dict()
    return draft_reply(row, intent, extra, cal, mode)

