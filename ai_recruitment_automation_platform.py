#Matching helper
def contains_relaxed(text: str, term: str) -> bool:
    if not term or not text: return False
    t = term.strip().lower(); body = text.lower()
    if t in body: return True
    return re.search(r"(?:^|[^a-z0-9])"+re.escape(t)+r"(?:[^a-z0-9]|$)", body) is not None

def safe_json(s: str):
    try:
        return json.loads(s)
    except Exception:
        m = re.search(r"\{.*\}", s, re.DOTALL)
        if m:
            try: return json.loads(m.group(0))
            except Exception: pass
    return {}

